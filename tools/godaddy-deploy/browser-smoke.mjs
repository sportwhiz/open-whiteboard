import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
import { createApi } from './api.mjs';
import { createInstallerServer } from './server.mjs';
import { providerFixture, release, token, passphrase } from './fixture.mjs';
const require = createRequire(new URL('../../apps/web/package.json', import.meta.url));
const { chromium } = require('playwright');
const fixture = providerFixture();
const reports = [];
let monitoringReady = true;
const monitor = { ready: async () => monitoringReady, record: async event => { reports.push(event); return true; }, resolve: async () => {} };
const origin = 'http://127.0.0.1:5306';
const server = createInstallerServer({ api: createApi({ release, fetchImpl: fixture.fetchImpl, monitor }), publicOrigin: origin });
await new Promise(resolve => server.listen(5306, '127.0.0.1', resolve));
const browser = await chromium.launch({ headless: true, ...(process.env.CHROME_PATH ? { executablePath: process.env.CHROME_PATH } : {}) });
const errors = [];
const context = await browser.newContext({ viewport: { width: 1280, height: 950 } });
try {
  const page = await context.newPage(); page.on('pageerror', error => errors.push(error.message));
  page.on('console', message => { if (message.type() === 'error' && !message.text().includes('Failed to load resource')) errors.push(message.text()); });
  await context.grantPermissions(['clipboard-read', 'clipboard-write']);
  await page.goto(origin);
  await page.getByText('Prefer to use Claude or Codex?', { exact: true }).click();
  await page.getByRole('button', { name: 'Copy setup instructions' }).click();
  await page.getByRole('status').filter({ hasText: 'Copied.' }).waitFor();
  const prompt = await page.evaluate(() => navigator.clipboard.readText());
  assert.ok(prompt.includes('gddy auth login')); assert.ok(prompt.includes('hosting.log:read'));
  const permissionCodes = await page.locator('#permissions code').allTextContents();
  assert.equal(permissionCodes.length, 9);
  assert.ok(permissionCodes.includes('hosting.log:read')); assert.ok(!prompt.includes(token));
  await page.screenshot({ path: '/tmp/open-whiteboard-godaddy-desktop.png', fullPage: true });
  await page.getByLabel('Paste your temporary key').fill('wrong-test-token');
  await page.getByRole('button', { name: 'Connect GoDaddy' }).click();
  await page.getByRole('alert').filter({ hasText: 'rejected this token' }).waitFor();
  assert.match(await page.getByRole('alert').innerText(), /Support reference: [a-f0-9-]{36}/);
  assert.deepEqual(Object.keys(reports[0]).sort(), ['action', 'attempt', 'category']);
  fixture.options.noPlans = true;
  await page.getByLabel('Paste your temporary key').fill(token);
  await page.getByRole('button', { name: 'Connect GoDaddy' }).click();
  await page.getByRole('alert').filter({ hasText: 'No available' }).waitFor();
  fixture.options.noPlans = false;
  await page.getByRole('button', { name: 'Connect GoDaddy' }).click();
  await page.getByLabel('Whiteboard name').waitFor();
  assert.equal(await page.getByLabel('Hosting plan').inputValue(), 'plan-one');
  assert.equal(await page.locator('#plan option[value="plan-full"]').isDisabled(), true);
  assert.equal(await page.locator('#token').inputValue(), '');
  await page.getByRole('button', { name: 'Disconnect' }).click();
  assert.equal(await page.locator('#token').inputValue(), '');
  await page.getByLabel('Paste your temporary key').fill(token);
  await page.getByRole('button', { name: 'Connect GoDaddy' }).click();
  await page.getByRole('button', { name: 'Make one for me' }).click();
  assert.ok((await page.getByLabel('Setup passphrase', { exact: true }).inputValue()).length >= 32);
  await page.getByRole('button', { name: 'Copy passphrase' }).click();
  assert.equal(await page.evaluate(() => navigator.clipboard.readText()), await page.getByLabel('Setup passphrase', { exact: true }).inputValue());
  await page.getByLabel('Setup passphrase', { exact: true }).fill(passphrase);
  await page.getByRole('button', { name: 'Deploy to GoDaddy' }).click();
  assert.equal(fixture.created, 0, 'Deployment began without a saved passphrase');
  await page.getByLabel('I’ve saved my setup passphrase.').check();
  await page.screenshot({ path: '/tmp/open-whiteboard-godaddy-connected.png', fullPage: true });
  // The provider creates an app but the first response is lost. Continue must reuse it.
  fixture.options.loseCreate = true;
  fixture.options.rejectConfigureOnce = true;
  await page.getByRole('button', { name: 'Deploy to GoDaddy' }).click();
  await page.getByRole('alert').filter({ hasText: 'could not be reached' }).waitFor();
  assert.equal(fixture.created, 1);
  await page.getByRole('button', { name: 'Continue deployment' }).click();
  await page.getByRole('heading', { name: 'Reconnect to continue', exact: true }).waitFor();
  assert.equal(fixture.created, 1);
  await page.getByLabel('Replacement temporary key', { exact: true }).fill('wrong-replacement-key');
  await page.getByRole('button', { name: 'Reconnect and continue', exact: true }).click();
  await page.getByRole('alert').filter({ hasText: 'rejected this token' }).waitFor();
  assert.equal(fixture.created, 1);
  await page.getByLabel('Replacement temporary key', { exact: true }).fill(token);
  await page.getByRole('button', { name: 'Reconnect and continue', exact: true }).click();
  await page.getByRole('heading', { name: 'Make yourself at home.' }).waitFor();
  assert.equal(fixture.created, 1);
  assert.equal(await page.getByRole('link', { name: 'Open my whiteboard' }).getAttribute('href'), 'https://fixture.c39.airoapp.ai');
  assert.equal(await page.locator('#passphrase').inputValue(), '');
  assert.equal(await page.locator('#reconnect-token').inputValue(), '');
  assert.deepEqual(await page.evaluate(() => ({ local: { ...localStorage }, session: { ...sessionStorage } })), { local: {}, session: {} });
  assert.equal((await context.cookies()).length, 0);
  assert.equal((await page.locator('body').innerText()).includes(token), false);
  await page.screenshot({ path: '/tmp/open-whiteboard-godaddy-success.png', fullPage: true });
  const mobile = await context.newPage(); await mobile.setViewportSize({ width: 390, height: 844 }); await mobile.goto(origin);
  await mobile.screenshot({ path: '/tmp/open-whiteboard-godaddy-mobile.png', fullPage: true });
  assert.equal(await mobile.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  await mobile.locator('#permissions').evaluate(el => { el.open = true; });
  assert.equal(await mobile.locator('#permissions li').first().evaluate(el => getComputedStyle(el, '::before').content), 'none', 'Permission rows must not increment the setup step counter');
  assert.equal(await mobile.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  monitoringReady = false;
  await mobile.goto(origin);
  await mobile.getByRole('heading', { name: 'The installer is temporarily unavailable.', exact: true }).waitFor();
  assert.equal(await mobile.locator('#connect-form').isVisible(), false);
  monitoringReady = true;
  const upstreamBeforePreview = fixture.calls.length;
  await mobile.goto(origin + '/?preview=1');
  await mobile.getByText('Interactive setup preview', { exact: true }).waitFor();
  assert.equal(await mobile.getByLabel('Paste your temporary key').getAttribute('readonly'), '');
  await mobile.getByRole('button', { name: 'Connect GoDaddy', exact: true }).click();
  await mobile.getByLabel('Whiteboard name').waitFor();
  assert.equal(await mobile.getByLabel('Setup passphrase', { exact: true }).getAttribute('readonly'), '');
  assert.equal(await mobile.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  await mobile.getByRole('button', { name: 'Disconnect', exact: true }).click();
  await mobile.getByRole('button', { name: 'Connect GoDaddy', exact: true }).click();
  await mobile.getByLabel('I’ve saved my setup passphrase.').check();
  await mobile.getByRole('button', { name: 'Preview deployment →', exact: true }).click();
  await mobile.getByRole('heading', { name: 'Next, make it yours.', exact: true }).waitFor();
  await mobile.getByRole('button', { name: 'See how automatic updates work →', exact: true }).click();
  await mobile.getByRole('button', { name: 'Use an example update connection', exact: true }).click();
  await mobile.getByRole('checkbox', { name: 'Install compatible security patches automatically', exact: true }).check();
  await mobile.getByRole('status').filter({ hasText: 'patches would install automatically' }).waitFor();
  assert.equal(await mobile.locator('[data-journey=account]').getAttribute('aria-current'), 'step');
  assert.equal(fixture.calls.length, upstreamBeforePreview, 'Preview contacted the hosting backend');
  assert.equal(await mobile.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  await mobile.screenshot({ path: '/tmp/open-whiteboard-godaddy-walkthrough-mobile.png', fullPage: true });
  assert.deepEqual(errors, []);
  console.log('Browser smoke passed: invalid token, unavailable plan, selection, disconnect, lost response recovery, mid-deployment key replacement, full deployment, credential clearing, desktop/mobile layouts, and a complete browser-only setup/update walkthrough with zero hosting requests.');
} finally { await context.close(); await browser.close(); await new Promise(resolve => server.close(resolve)); }
